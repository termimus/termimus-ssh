import { useEffect, useRef, useState } from "react";
import { ShieldAlert, AlertTriangle, X, Play, Server } from "lucide-react";
import { AiRiskLevel } from "../../lib/api";

/** Host tags that mark a server as production (case-insensitive). */
const PRODUCTION_TAGS = new Set(["prod", "production", "prd", "live"]);

export function isProductionHost(tags: string[] | undefined | null): boolean {
  return !!tags?.some((t) => PRODUCTION_TAGS.has(t.trim().toLowerCase()));
}

/**
 * Gate for running an AI-generated command:
 * - destructive → always confirm
 * - production host + modifying/destructive → confirm by typing the host label
 * - otherwise → run directly
 */
export function runConfirmationFor(
  risk: AiRiskLevel,
  isProduction: boolean
): "none" | "click" | "type" {
  if (isProduction && risk !== "safe") return "type";
  if (risk === "destructive") return "click";
  return "none";
}

export interface PendingRun {
  /** Terminal the command will be written to (captured when the dialog opens). */
  sessionId: string;
  command: string;
  risk: AiRiskLevel;
  reasons: string[];
  explanation?: string;
  targetLabel: string;
  targetAddress?: string;
  isProduction: boolean;
  mode: "click" | "type";
  /** Extra warning, e.g. the command was generated for a different terminal. */
  note?: string;
}

interface Props {
  pending: PendingRun | null;
  onCancel: () => void;
  onConfirm: () => void;
}

export function AiRunConfirmDialog({ pending, onCancel, onConfirm }: Props) {
  const [typed, setTyped] = useState("");
  const inputRef = useRef<HTMLInputElement>(null);
  const cancelRef = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    setTyped("");
    if (!pending) return;
    // Focus the safe choice by default; the typed gate focuses its input.
    const t = setTimeout(() => {
      if (pending.mode === "type") inputRef.current?.focus();
      else cancelRef.current?.focus();
    }, 30);
    return () => clearTimeout(t);
  }, [pending]);

  useEffect(() => {
    if (!pending) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") {
        e.preventDefault();
        onCancel();
      }
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [pending, onCancel]);

  if (!pending) return null;

  const destructive = pending.risk === "destructive";
  const canConfirm = pending.mode === "click" || typed.trim() === pending.targetLabel.trim();

  return (
    <div
      onClick={(e) => {
        if (e.target === e.currentTarget) onCancel();
      }}
      className="fixed inset-0 z-[60] flex items-center justify-center bg-black/70 backdrop-blur-sm p-4 animate-in fade-in duration-150"
    >
      <div
        role="alertdialog"
        aria-modal="true"
        aria-label="Confirm running AI-generated command"
        className="w-full max-w-md rounded-2xl border border-[var(--border)] bg-[var(--surface-low)] p-5 shadow-2xl animate-in zoom-in-95 duration-150"
      >
        <div className="flex items-start justify-between mb-3">
          <div className="flex items-center gap-3">
            <div
              className={`flex h-10 w-10 shrink-0 items-center justify-center rounded-xl border ${
                destructive
                  ? "bg-[var(--danger)]/15 text-[var(--danger)] border-[var(--danger)]/30"
                  : "bg-[var(--warning)]/15 text-[var(--warning)] border-[var(--warning)]/30"
              }`}
            >
              {destructive ? <ShieldAlert size={18} /> : <AlertTriangle size={18} />}
            </div>
            <div>
              <h3 className="text-sm font-semibold text-[var(--text-primary)]">
                {destructive ? "Run destructive command?" : "Run command on production?"}
              </h3>
              <p className="text-[11px] text-[var(--text-muted)]">
                Generated by AI — review it before running.
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={onCancel}
            className="rounded-lg p-1 text-[var(--text-muted)] hover:bg-[var(--surface-high)] hover:text-[var(--text-primary)] transition cursor-pointer"
          >
            <X size={16} />
          </button>
        </div>

        {/* Target */}
        <div className="flex items-center gap-2 mb-2.5 text-xs">
          <Server size={13} className="text-[var(--primary)] shrink-0" />
          <span className="text-[var(--text-secondary)]">Target:</span>
          <span className="font-mono font-semibold text-[var(--text-primary)] truncate">
            {pending.targetLabel}
          </span>
          {pending.targetAddress && (
            <span className="font-mono text-[var(--text-muted)] truncate">
              ({pending.targetAddress})
            </span>
          )}
          {pending.isProduction && (
            <span className="ml-auto shrink-0 rounded-full border border-[var(--danger)]/40 bg-[var(--danger)]/15 px-1.5 py-0.5 text-[9px] font-bold uppercase tracking-wider text-[var(--danger)]">
              Production
            </span>
          )}
        </div>

        {pending.note && (
          <div className="mb-2.5 flex items-start gap-1.5 rounded-lg border border-[var(--warning)]/30 bg-[var(--warning)]/10 p-2 text-[11px] text-[var(--warning)]">
            <AlertTriangle size={12} className="mt-0.5 shrink-0" />
            <span>{pending.note}</span>
          </div>
        )}

        {/* Command */}
        <pre className="mb-2.5 max-h-40 overflow-auto whitespace-pre-wrap break-all rounded-xl border border-[var(--border)] bg-[var(--canvas)] p-2.5 font-mono text-xs text-[var(--primary)]">
          {pending.command}
        </pre>

        {pending.explanation && (
          <p className="mb-2.5 text-[11px] leading-relaxed text-[var(--text-secondary)]">
            {pending.explanation}
          </p>
        )}

        {pending.reasons.length > 0 && (
          <ul className="mb-3 space-y-0.5 text-[11px] text-[var(--text-secondary)]">
            {pending.reasons.map((r) => (
              <li key={r} className="flex items-center gap-1.5">
                <span
                  className={`h-1 w-1 shrink-0 rounded-full ${
                    destructive ? "bg-[var(--danger)]" : "bg-[var(--warning)]"
                  }`}
                />
                {r}
              </li>
            ))}
          </ul>
        )}

        {pending.mode === "type" && (
          <div className="mb-3">
            <label className="mb-1 block text-[11px] text-[var(--text-secondary)]">
              Type <span className="font-mono font-semibold text-[var(--text-primary)]">{pending.targetLabel}</span> to confirm
            </label>
            <input
              ref={inputRef}
              value={typed}
              onChange={(e) => setTyped(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === "Enter" && canConfirm) {
                  e.preventDefault();
                  onConfirm();
                }
              }}
              spellCheck={false}
              autoComplete="off"
              className="w-full rounded-xl border border-[var(--border)] bg-[var(--surface-container)] px-3 py-1.5 font-mono text-xs text-[var(--text-primary)] focus:border-[var(--danger)]/60 focus:outline-hidden"
            />
          </div>
        )}

        <div className="flex items-center justify-end gap-2 border-t border-[var(--border)] pt-3.5">
          <button
            ref={cancelRef}
            type="button"
            onClick={onCancel}
            className="rounded-xl border border-[var(--border)] bg-[var(--surface-container)] px-3.5 py-1.5 text-xs font-medium text-[var(--text-secondary)] hover:bg-[var(--surface-high)] hover:text-[var(--text-primary)] transition cursor-pointer"
          >
            Cancel
          </button>
          <button
            type="button"
            disabled={!canConfirm}
            onClick={onConfirm}
            className={`flex items-center gap-1.5 rounded-xl px-4 py-1.5 text-xs font-semibold transition shadow-sm disabled:opacity-40 disabled:cursor-not-allowed cursor-pointer ${
              destructive
                ? "bg-[var(--danger)] text-white hover:opacity-90"
                : "bg-[var(--warning)] text-black hover:opacity-90"
            }`}
          >
            <Play size={12} className="fill-current" />
            Run anyway
          </button>
        </div>
      </div>
    </div>
  );
}
